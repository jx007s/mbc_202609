## 권장하지 않음
print(c)
print(d)
print(e)
print(c,d,e)  ## 동시에 여러내용 출력가능 : 권장하지 않음- 띄어쓰기 간격을 조절할 수 없음
print("c:",c)
print("d:",d)
print("e:",e)

