## 변수 선언 및 초기화
b = 10
# 변수명 : b
# 변수대입값 : 10
# 대입 : 대입연산자 우항의 값(연산결과 포함)을 복사하여 변수가 가리키는 공간에 값을 넣는 작업
print(b) # 변수호출
# 호출 : 변수가 가리키는 공간의 값을 복사해서 가져와 사용

b = 20  ## 변수 대입 : 기존의 변수값(10)은 삭제되고 새로운 대입값(20)으로 대체
print(b) # 변수호출

c = 30 ; d = 40 ; e = 50
