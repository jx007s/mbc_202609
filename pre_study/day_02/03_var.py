'''
수학
	5 + 3 = x

	5 , 3 : 변하지 않는 값 => 상수	
	x      : 값을 담을수 있는 공간 => 변수
       상수, 변수 : 연산을 하기 위한 재료

	+   : 산술 연산자
	=   : 대입 연산자
       연산자 : 항(보통 상수나 변수 혹은 연산결과)을 재료로 하여 작업(연산)
       
프로그램
	5 + 3 = x  에러발생
	x = 5 + 3  정상실행  ::> 대입연산자 좌항에 변수 위치

'''

#5 + 3 = x  에러발생
x = 5 + 3
print(x)

